def seed_voter(conn,voter,election,token,now,fixture_actor):
    """Fixture-only, after connection identity/disposable-marker verification."""
    conn.execute("INSERT INTO ra.voters(voter_id,auth_provider,auth_subject,is_active) VALUES(%s,%s,%s,true)",
        (voter,"gate2-disposable-test",str(voter)))
    # eligibility_id has no default in the applied schema. The trusted owner
    # function generates it and audits the grant in this fixture transaction.
    check(conn.execute("SELECT ra.set_voter_eligibility(%s,%s,true,%s)",
        (voter,election,fixture_actor)).fetchone()==(True,),"Fixture eligibility grant failed")
    row=conn.execute("SELECT eligibility_id,is_eligible FROM ra.voter_eligibility WHERE voter_id=%s AND election_id=%s",
        (voter,election)).fetchone()
    check(row is not None and isinstance(row[0],UUID) and row[1] is True,
          "Fixture eligibility identifier or activation missing")
    conn.execute("SELECT ra.create_session(%s,%s,%s,%s)",
        (DemoSessionService._digest(token),voter,now,now+timedelta(minutes=15)))


def exercise(fixture,runtime,signer_binary,node):
    election=uuid4()
    fixture_actor=uuid4()  # Opaque per-run fixture service, separate from runtime audit identity.
    voters=[uuid4() for _ in range(14)]
    tokens=[secrets.token_urlsafe(32) for _ in voters]
    signing=rsa.generate_private_key(public_exponent=65537,key_size=3072)
    tally=rsa.generate_private_key(public_exponent=65537,key_size=3072)
    authority=ed25519.Ed25519PrivateKey.generate()
    pin=authority.public_key().public_bytes(serialization.Encoding.Raw,serialization.PublicFormat.Raw)
    def spki(key):
        return key.public_key().public_bytes(serialization.Encoding.DER,serialization.PublicFormat.SubjectPublicKeyInfo)
    manifest=make_manifest({"spki":b64encode(spki(signing))},{"spki":b64encode(spki(tally))})
    manifest["election_id"]=str(election)
    manifest["ra_key"]["key_id"]="gate2-test-"+election.hex
    seeded=False
    signer=client=None
    try:
        with fixture() as conn:
            check(conn.execute("SELECT version_num FROM ra.alembic_version").fetchone()==(HEAD,),
                  "Reviewed Gate 2 migration not installed")
            now=conn.execute("SELECT clock_timestamp()").fetchone()[0].replace(microsecond=0)
            manifest["opens_at"]=(now-timedelta(hours=1)).strftime("%Y-%m-%dT%H:%M:%SZ")
            manifest["closes_at"]=(now+timedelta(hours=1)).strftime("%Y-%m-%dT%H:%M:%SZ")
            bundle=signed_bundle(manifest,authority)
            raw=canonical_manifest(manifest)
            config_hash=hashlib.sha256(raw).digest()
            seeded=True  # Cleanup our generated UUIDs even if setup commit outcome is uncertain.
            for voter,token in zip(voters,tokens):
                seed_voter(conn,voter,election,token,now,fixture_actor)
            conn.execute("""INSERT INTO ra.ra_signing_keys(ra_key_id,election_id,public_key_spki_der,
                public_key_fingerprint,private_key_reference,key_state,activated_at)
                VALUES(%s,%s,%s,%s,%s,'ACTIVE',%s)""",
                (manifest["ra_key"]["key_id"],election,spki(signing),hashlib.sha256(spki(signing)).digest(),
                 "ephemeral-disposable-test-key-in-memory",now))
            conn.execute("""INSERT INTO ra.credential_policies(election_id,ra_key_id,manifest_bytes,manifest_signature,
                config_hash,key_fingerprint,opens_at,closes_at,issuance_enabled) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,true)""",
                (election,manifest["ra_key"]["key_id"],raw,b64decode(bundle["signature"]),config_hash,
                 hashlib.sha256(spki(signing)).digest(),now-timedelta(hours=1),now+timedelta(hours=1)))
        signer=LocalCIRCLSigner(signer_binary,signing,manifest["ra_key"]["key_id"])
        client=Peer([str(node),str(Path(__file__).resolve().parents[1]/"crypto_interop/dist/client.js")],"Test TS client")
        store=FaultStore(runtime)
        service=CredentialIssuanceService(store,signer,CredentialRecovery({"test-only":secrets.token_bytes(32)},"test-only"),pin)
        # In-process HTTP exercises the real route/service/DB. This is not a network listener.
        app=FastAPI()
        app.include_router(router)
        app.dependency_overrides[get_credential_service]=lambda:service
        with TestClient(app) as http:
            def prepare():
                return client.call({"op":"prepare","bundle":bundle,"pinned_root":b64encode(pin),
                    "expected_election":str(election),"envelope_hash":"a"*64})
            def body(prepared,request=None):
                return {"election_id":str(election),"request_id":str(request or uuid4()),
                        "blinded_msg":prepared["blinded_msg"]}
            def post(index,data):
                return http.post(ISSUE,json=data,headers={"Authorization":"Bearer "+tokens[index]})

            prepared=prepare(); data=body(prepared)
            first=post(0,data)
            check(first.status_code==201,"Authorized issuance failed")
            repeated=post(0,data)
            check(repeated.status_code==200 and repeated.json()["blind_sig"]==first.json()["blind_sig"],"Exact retry differed")
            proof=client.call({"op":"finalize","handle":prepared["handle"],"blind_sig":first.json()["blind_sig"]})
            verify_credential(proof,bundle,pin,str(election),"a"*64)
            check(post(0,body(prepare())).status_code==409,"Second independent credential accepted")
            check(post(1,data).status_code==201,"Second voter isolation failed")
            with fixture() as conn:
                check(conn.execute("SELECT count(*) FROM ra.blind_issuances WHERE voter_id=ANY(%s)",(voters[:2],)).fetchone()==(2,),
                      "One-voter authorization count mismatch")
                check(conn.execute("""SELECT actor_type,actor_principal_id,event_type,outcome
                    FROM ra.ra_audit_events WHERE voter_id=%s AND election_id=%s
                    AND event_type='BLIND_ISSUANCE_ISSUED'""",(voters[0],election)).fetchall()==[
                        ("SERVICE",UUID("00000000-0000-4000-8000-000000000002"),"BLIND_ISSUANCE_ISSUED","SUCCESS")],
                    "Runtime issuance service audit identity mismatch")
                cipher=conn.execute("SELECT encrypted_blind_signature FROM ra.blind_issuances WHERE voter_id=%s",(voters[0],)).fetchone()[0]
                check(len(cipher)==400 and bytes(cipher)!=b64decode(first.json()["blind_sig"]),"Recovery data not protected")
            print("PASS: real TS -> authenticated issuance -> CIRCL -> TS Finalize -> Python; exact recovery and voter isolation")

            pair=[body(prepare()),body(prepare())]
            with ThreadPoolExecutor(max_workers=2) as pool:
                results=list(pool.map(lambda value:post(2,value).status_code,pair))
            check(sorted(results)==[201,409],"Concurrent independent requests were not exclusive")
            exact=body(prepare())
            with ThreadPoolExecutor(max_workers=2) as pool:
                results=list(pool.map(lambda _:post(3,exact).status_code,range(2)))
            check(sorted(results)==[200,201],"Concurrent identical retries failed")
            print("PASS: PostgreSQL concurrency for different and identical requests")

            for index,mode in ((4,"after_reservation"),(5,"before_commit"),(6,"after_commit")):
                data=body(prepare()); store.mode=mode
                check(post(index,data).status_code==503,"Injected failure reported success")
                store.mode=None
                check(post(index,body(prepare())).status_code==409,"Failure released authorization")
                check(post(index,data).status_code==(200 if mode=="after_commit" else 201),"Exact crash recovery failed")
            original_sign=signer.sign
            data=body(prepare())
            service.signer=Mock(matches=Mock(return_value=True),sign=Mock(side_effect=CredentialUnavailable()))
            check(post(7,data).status_code==503,"Signer failure accepted")
            check(post(7,body(prepare())).status_code==409,"Signer failure reset eligibility")
            service.signer=signer
            check(post(7,data).status_code==201,"Retry after signer failure failed")
            def crash_after_sign(original):
                original_sign(original)
                raise CredentialUnavailable()
            service.signer=Mock(matches=Mock(return_value=True),sign=Mock(side_effect=crash_after_sign))
            data=body(prepare())
            check(post(8,data).status_code==503,"Lost signing response accepted")
            service.signer=signer
            check(post(8,data).status_code==201,"Crash after signing was not recoverable")
            print("PASS: reservation/signing/commit crash boundaries and lost committed response recovery")

            with fixture() as conn:
                check(conn.execute("SELECT ra.set_voter_eligibility(%s,%s,false,%s)",
                    (voters[9],election,fixture_actor)).fetchone()==(True,),"Fixture eligibility revocation failed")
                check(conn.execute("SELECT ra.disable_voter(%s,%s)",
                    (voters[10],fixture_actor)).fetchone()==(True,),"Fixture voter disablement failed")
                conn.execute("UPDATE ra.ra_sessions SET created_at=%s,expires_at=%s WHERE voter_id=%s",
                    (now-timedelta(hours=1),now-timedelta(minutes=1),voters[11]))
                conn.execute("UPDATE ra.ra_sessions SET revoked_at=clock_timestamp() WHERE voter_id=%s",(voters[12],))
                # Pre-expired fixture reservation is inserted explicitly, never mutating an existing slot.
                expired=body(prepare())
                conn.execute("""INSERT INTO ra.credential_reservations(voter_id,election_id,request_id,blinded_request_hash,
                    ra_key_id,config_hash,reserved_at,recovery_expires_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s)""",
                    (voters[13],election,expired["request_id"],hashlib.sha256(b64decode(expired["blinded_msg"])).digest(),
                     manifest["ra_key"]["key_id"],config_hash,now-timedelta(days=2),now-timedelta(days=1)))
            for index,status in ((9,403),(10,401),(11,401),(12,401)):
                check(post(index,body(prepare())).status_code==status,"Invalid eligibility or session accepted")
            check(post(13,expired).status_code==410,"Expired recovery accepted")
            check(post(13,body(prepare())).status_code==409,"Expiry released authorization")
            malformed=body(prepare()); malformed["blinded_msg"]=b64encode(bytes(384))
            check(post(0,malformed).status_code==422,"Malformed blinded message accepted")
            original_pin=service._authority
            service._authority=secrets.token_bytes(32)
            check(post(0,data).status_code==503,"Incorrect manifest trust pin accepted")
            service._authority=original_pin

        with fixture() as conn:
            # Preserve enrolled policy/key metadata; operators cannot quietly
            # substitute a new key or reopen an election by editing its row.
            try:
                with conn.transaction():
                    conn.execute("UPDATE ra.credential_policies SET closes_at=closes_at+interval '1 hour' WHERE election_id=%s",(election,))
            except psycopg.errors.RaiseException:
                pass
            else:
                raise AssertionError("Mutable enrolled policy")
            try:
                with conn.transaction():
                    conn.execute("UPDATE ra.ra_signing_keys SET public_key_spki_der=%s WHERE election_id=%s",(spki(tally),election))
            except psycopg.errors.RaiseException:
                pass
            else:
                raise AssertionError("Mutable enrolled key material")

        with runtime() as conn:
            rows=conn.execute("""SELECT p.proname,p.prosecdef,r.rolname,p.proconfig,
                has_function_privilege(current_user,p.oid,'EXECUTE')
                FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
                JOIN pg_roles r ON r.oid=p.proowner WHERE n.nspname='ra_credential'""").fetchall()
            check({r[0] for r in rows if r[4]}==EXPORTED,"Unexpected runtime function surface")
            check(all(r[1] and r[2]=="ra_owner" and "search_path=pg_catalog,ra,pg_temp" in "".join("".join(r[3] or []).split())
                      for r in rows),"Unsafe definer function")
        for sql in ("SELECT * FROM ra.voters LIMIT 0","SELECT * FROM ra.credential_reservations LIMIT 0",
                    "SELECT ra.find_active_session(repeat('a',64))","SELECT ra_credential._voter(repeat('a',64))",
                    "SET ROLE ra_owner","SET ROLE ra_migrator_login"):
            assert_denied(runtime,sql)
        print("PASS: expiry tombstones, session/eligibility denial, malformed input, restricted database access")
    finally:
        try:
            if client is not None:
                client.close()
        finally:
            try:
                if signer is not None:
                    signer.close()
            finally:
                if seeded:
                    with fixture() as conn:
                        cleanup(conn,voters,election)


