def issuance_factory(password,*,database,marker,port):
    validate_disposable_designation(database,marker)
    check(1<=port<=65535,"Invalid port")
    def connect():
        conn=psycopg.connect(host="127.0.0.1",port=port,dbname=database,user="ra_issuance_login",
            password=password.get_secret_value(),connect_timeout=5,
            options="-c statement_timeout=5000 -c lock_timeout=2000")
        try:
            check(conn.execute("SELECT current_database(),session_user,current_user").fetchone()==
                (database,"ra_issuance_login","ra_issuance_login"),"Incorrect runtime identity")
            verify_disposable_database(conn,database,marker)
            return conn
        except BaseException:
            conn.close()
            raise
    return connect


class FaultStore(PostgreSQLCredentialStore):
    """Process/response loss injection at actual PostgreSQL commit boundaries."""
    mode=None
    def reserve(self,*params):
        result=super().reserve(*params)
        if self.mode=="after_reservation":
            raise CredentialUnavailable()
        return result

    @contextmanager
    def locked(self,*params):
        with super().locked(*params) as transaction:
            yield transaction
            if self.mode=="before_commit":
                raise CredentialUnavailable()
        if self.mode=="after_commit":
            raise CredentialUnavailable()


def assert_denied(factory,sql):
    try:
        with factory() as conn:
            conn.execute(sql)
    except psycopg.errors.InsufficientPrivilege:
        return
    raise AssertionError("Unauthorized operation accepted")


